#!/usr/bin/env python3
"""Canopy glass triangles (eye-relative) of the cockpit ships for the engine's cockpit_glass.cpp.
usage: gen_glass_data.py <models dir with the exterior POFs> > code/graphics/cockpit_glass_data.h"""
import struct, sys
import numpy as np, importlib.util
sys.argv, models = sys.argv[:1], sys.argv[1]
spec = importlib.util.spec_from_file_location('pv', __file__.replace('gen_glass_data.py', 'pofview.py'))
pv = importlib.util.module_from_spec(spec); spec.loader.exec_module(pv)


def info(path):
    d = open(path, 'rb').read(); p = 8; names = []; eye = None
    while p < len(d):
        tag = d[p:p + 4]; ln = struct.unpack('<i', d[p + 4:p + 8])[0]
        if tag == b'TXTR':
            n = struct.unpack('<i', d[p + 8:p + 12])[0]; q = p + 12
            for _ in range(n):
                l = struct.unpack('<i', d[q:q + 4])[0]; names.append(d[q + 4:q + 4 + l].decode()); q += 4 + l
        if tag == b'EYE ' and eye is None:
            eye = np.array(struct.unpack('<3f', d[p + 16:p + 28]))
        p += 8 + ln
    return names, eye


def glass(ship, near=None):
    names, eye = info(models + '/' + ship)
    P, N, UV, TM, FN = pv.collect(pv.read_pof(models + '/' + ship))
    sel = [i for i, n in enumerate(names) if 'glass' in n.lower()]
    tris = P[np.isin(TM, sel)] - eye
    if near is not None:                       # only the glass around the pilot
        c = tris.mean(axis=1)
        tris = tris[(np.abs(c[:, 0]) < near[0]) & (c[:, 1] > near[1]) & (np.abs(c[:, 2]) < near[2])]
    return tris


# cockpit POF name -> glass; the VIIe model has no glass of its own, it shares the VII's canopy
viper = glass('Col_Viper_Mk7.pof')
raptor = glass('Col_Raptor.pof', near=(1.6, -1.2, 3.2))
data = [('Col_Viper_Mk7_CP.pof', viper), ('Col_Viper_Mk7e_CP.pof', viper), ('Col_Raptor_CP.pof', raptor)]
print('// Generated by tools/gen_glass_data.py: canopy glass triangles in metres, relative to the pilot\'s eye (x right, y up, z forward).')
print('#pragma once\n')
print('struct CockpitGlass {\n\tconst char* cockpit_pof;\n\tint n_tris;\n\tconst float* v;\t// n_tris * 9 floats\n};\n')
for i, (name, t) in enumerate(data):
    print('static const float Glass_%d[] = {' % i)
    for tri in t:
        print('\t' + ', '.join('%.4ff' % x for x in tri.reshape(-1)) + ',')
    print('};')
print('\nstatic const CockpitGlass Cockpit_glass[] = {')
for i, (name, t) in enumerate(data):
    print('\t{ "%s", %d, Glass_%d },' % (name, len(t), i))
print('};')
